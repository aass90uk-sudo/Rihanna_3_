# ============================================================
# معرفة هل الرسالة سؤال
# ============================================================

def looks_like_question(
    text: str
) -> bool:

    if not text:
        return False

    text = text.strip().lower()

    # وجود علامة استفهام
    if "?" in text or "؟" in text:
        return True

    # كلمات السؤال
    question_words = [

        "هل ",

        "كيف ",

        "ما حكم",

        "ماهو",

        "ما هو",

        "ماذا ",

        "لماذا ",

        "حكم ",

        "يجوز",

        "حرام",

        "حلال",

        "أريد أن أعرف",

        "واش ",

        "علاش ",

        "كيفاش ",

        "وش ",

        "نقدر ",

        "واش نقدر",

        "هل يجوز",

    ]

    return any(
        text.startswith(word)
        for word in question_words
    )


# ============================================================
# التعامل مع رسائل المجموعة فقط
#
# مهم جدًا:
#
# هذا المعالج لا يعمل مع القناة.
#
# فهو مقيد بـ:
#
# filters.ChatType.GROUPS
#
# لذلك:
#
# قناة = نشر فقط
# مجموعة = تفاعل وردود
# ============================================================

async def handle_group_message(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE,
):

    # التأكد من وجود رسالة
    if not update.message:
        return

    message = update.message

    # ========================================================
    # حماية إضافية:
    # لا نتعامل إلا مع GROUP / SUPERGROUP
    # ========================================================

    if message.chat.type not in (
        ChatType.GROUP,
        ChatType.SUPERGROUP,
    ):
        return

    # الحصول على النص
    text = (
        message.text
        or message.caption
        or ""
    )

    if not text.strip():
        return

    # ========================================================
    # الحصول على معلومات البوت
    # ========================================================

    bot = await context.bot.get_me()

    # ========================================================
    # هل تم ذكر البوت؟
    # ========================================================

    mentioned = False

    if bot.username:

        mentioned = (
            f"@{bot.username.lower()}"
            in text.lower()
        )

    # ========================================================
    # هل الرسالة رد على رسالة البوت؟
    # ========================================================

    replied_to_bot = False

    if message.reply_to_message:

        if message.reply_to_message.from_user:

            replied_to_bot = (
                message.reply_to_message
                .from_user
                .id
                == bot.id
            )

    # ========================================================
    # هل الرسالة سؤال؟
    # ========================================================

    question = looks_like_question(
        text
    )

    # ========================================================
    # البوت لا يتدخل إلا في الحالات التالية:
    #
    # 1. سؤال
    # 2. منشن للبوت
    # 3. رد على رسالة البوت
    # ========================================================

    if not (
        question
        or mentioned
        or replied_to_bot
    ):
        return

    # ========================================================
    # إزالة منشن البوت من النص
    # ========================================================

    if bot.username:

        mention = f"@{bot.username}"

        text = text.replace(
            mention,
            ""
        ).strip()

    # ========================================================
    # إذا بقي النص فارغًا
    # ========================================================

    if not text:

        text = (
            "أخي، تفضل اطرح سؤالك "
            "وإن شاء الله نحاول نعاونك."
        )

    # ========================================================
    # تحديد صاحب المحادثة
    # ========================================================

    user = message.from_user

    if user:

        chat_key = (
            f"{message.chat.id}:"
            f"{user.id}"
        )

    else:

        chat_key = str(
            message.chat.id
        )

    logger.info(
        "💬 سؤال جديد في المجموعة | %s",
        text[:200],
    )

    # ========================================================
    # إرسال السؤال إلى الذكاء الاصطناعي
    # ========================================================

    answer = await ask_ai(
        text,
        chat_key=chat_key,
    )

    # ========================================================
    # الرد على رسالة العضو
    # ========================================================

    try:

        await message.reply_text(
            answer,
            disable_web_page_preview=True,
        )

        logger.info(
            "✅ تم الرد على العضو في المجموعة."
        )

    except Exception:

        logger.exception(
            "❌ فشل إرسال الرد في المجموعة."
        )


