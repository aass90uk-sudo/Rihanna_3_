# ============================================================
# تشغيل جدولة النشر
# ============================================================

async def post_scheduler(
    application: Application
):

    # انتظار قصير بعد تشغيل البوت
    await asyncio.sleep(30)

    # بدء دورة النشر
    await scheduled_publisher(
        application
    )


# ============================================================
# Post Init
# ============================================================

async def post_init(
    application: Application
):

    asyncio.create_task(
        post_scheduler(
            application
        )
    )


